/** 按 era 分组 */
export interface DynastyGroup {
  era: string
  items: Dynasty[]
}

export function groupByEra(): DynastyGroup[] {
  const map = new Map<string, Dynasty[]>()
  for (const d of dynasties) {
    if (!map.has(d.era)) map.set(d.era, [])
    map.get(d.era)!.push(d)
  }
  const order = ['先秦', '汉', '隋唐', '宋辽金夏', '明清']
  return order
    .filter((key) => map.has(key))
    .map((key) => ({ era: key, items: map.get(key)! }))
}

